const dictionaries: Record<Lang, Dict> = { uk: UK, en: EN };

// External locale overrides: завантажуються з %APPDATA%/.../locales/{uk,en}.json
// при старті програми. Дозволяє користувачам править/доповнювати переклади без
// перебудови додатку. Ключі з зовнішнього файлу перекривають вбудовані.
export async function loadExternalLocales(): Promise<{ uk: number; en: number }> {
  const merged = { uk: 0, en: 0 };
  try {
    const w = (window as unknown as { dp2?: { readLocaleFile?: (lang: string) => Promise<Record<string, string> | null> } }).dp2;
    if (!w?.readLocaleFile) return merged;
    for (const lang of ["uk", "en"] as Lang[]) {
      try {
        const ext = await w.readLocaleFile(lang);
        if (ext && typeof ext === "object") {
          Object.assign(dictionaries[lang], ext);
          merged[lang] = Object.keys(ext).length;
        }
      } catch {}
    }
    if (merged.uk + merged.en > 0) listeners.forEach((fn) => fn());
  } catch {}
  return merged;
}

let currentLang: Lang = DEFAULT_LANG;
try {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === "uk" || stored === "en") {
    currentLang = stored;
  } else {
    // Перший запуск — авто-детект з браузера: якщо мова системи не схожа
    // на українську, дефолтимо у EN, щоб onboarding-лог теж був англ.
    const navLang = (typeof navigator !== "undefined" && navigator.language) ? navigator.language.toLowerCase() : "";
    if (navLang && !/^uk\b|^ua\b/.test(navLang)) currentLang = "en";
  }
} catch {}

const listeners = new Set<() => void>();

export function getLang(): Lang {
  return currentLang;
}

export function setLang(l: Lang) {
  currentLang = l;
  try { localStorage.setItem(STORAGE_KEY, l); } catch {}
  listeners.forEach((fn) => fn());
}

export function t(key: string, params?: Record<string, string | number>): string {
  const d = dictionaries[currentLang] || UK;
  let s = d[key] ?? UK[key] ?? key;
  if (params) {
    for (const k in params) {
      s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(params[k]));
    }
  }
  return s;
}

/** React hook: повертає актуальну `t` і ре-рендерить компонент при зміні мови. */
export function useT(): typeof t {
  const [, force] = useState(0);
  useEffect(() => {
    const cb = () => force((x) => x + 1);
    listeners.add(cb);
    return () => { listeners.delete(cb); };
  }, []);
  return t;
}
